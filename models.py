from datetime import datetime

from flask_sqlalchemy import SQLAlchemy
from flask_login import UserMixin


db = SQLAlchemy()


# ============================================================
# USER
# ============================================================

class User(db.Model, UserMixin):

    id = db.Column(
        db.Integer,
        primary_key=True
    )

    username = db.Column(
        db.String(100),
        unique=True,
        nullable=False
    )

    email = db.Column(
        db.String(120),
        unique=True,
        nullable=False
    )

    # Nullable because Google users may not have a password
    password = db.Column(
        db.String(200),
        nullable=True
    )

    is_admin = db.Column(
        db.Boolean,
        default=False
    )

    google_id = db.Column(
        db.String(100),
        unique=True,
        nullable=True
    )

    profile_picture = db.Column(
        db.String(300),
        nullable=True
    )

    # ========================================================
    # INVITATION CAMPAIGN
    # ========================================================

    # Permanent invitation code belonging to this user.
    #
    # Example:
    # MZ-AB12CD
    #
    # The code will not change.
    invitation_code = db.Column(
        db.String(30),
        unique=True,
        nullable=True
    )

    # ID of the user who invited this user.
    #
    # NULL means the user joined without an inviter.
    #
    # Example:
    #
    # User A
    # id = 1
    #
    # User B
    # invited_by_id = 1
    #
    invited_by_id = db.Column(
        db.Integer,
        db.ForeignKey(
            'user.id',
            ondelete='SET NULL'
        ),
        nullable=True
    )

    # When the account was created.
    #
    # This is used for the 10-day invitation-code
    # entry restriction.
    registered_at = db.Column(
        db.DateTime,
        default=datetime.utcnow,
        nullable=False
    )

    # --------------------------------------------------------
    # USER WHO INVITED THIS USER
    # --------------------------------------------------------

    inviter = db.relationship(
        'User',
        remote_side=[id],
        foreign_keys=[invited_by_id],
        backref=db.backref(
            'invited_users',
            lazy=True
        )
    )

    # --------------------------------------------------------
    # USER PURCHASES
    # --------------------------------------------------------

    purchases = db.relationship(
        'Purchase',
        backref='user',
        lazy=True,
        cascade='all, delete-orphan'
    )

    # --------------------------------------------------------
    # REFERRAL PURCHASES GENERATED BY THIS USER'S INVITEES
    # --------------------------------------------------------

    referral_purchases = db.relationship(
        'ReferralPurchase',
        foreign_keys='ReferralPurchase.inviter_id',
        backref='inviter',
        lazy=True,
        cascade='all, delete-orphan'
    )

    # --------------------------------------------------------
    # REWARDS EARNED BY THIS USER
    # --------------------------------------------------------

    rewards = db.relationship(
        'Reward',
        foreign_keys='Reward.user_id',
        backref='user',
        lazy=True,
        cascade='all, delete-orphan'
    )

    # --------------------------------------------------------
    # AVAILABLE REWARD COUNT
    # --------------------------------------------------------

    def available_rewards(self):

        """
        Return the number of unused free rewards
        currently available to this user.
        """

        return Reward.query.filter_by(
            user_id=self.id,
            status='Available'
        ).count()


