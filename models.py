# ============================================================
# PURCHASE
# ============================================================

class Purchase(db.Model):

    id = db.Column(
        db.Integer,
        primary_key=True
    )

    # --------------------------------------------------------
    # USER
    # --------------------------------------------------------

    user_id = db.Column(
        db.Integer,
        db.ForeignKey('user.id'),
        nullable=False
    )

    # --------------------------------------------------------
    # MOVIE
    # --------------------------------------------------------
    # NULL when purchase is for a series

    video_id = db.Column(
        db.Integer,
        db.ForeignKey('video.id'),
        nullable=True
    )

    # --------------------------------------------------------
    # SERIES
    # --------------------------------------------------------
    # NULL when purchase is for a movie

    series_id = db.Column(
        db.Integer,
        db.ForeignKey('series.id'),
        nullable=True
    )

    # --------------------------------------------------------
    # ITEM TYPE
    # --------------------------------------------------------
    # "movie" or "series"

    item_type = db.Column(
        db.String(20),
        nullable=False
    )

    # --------------------------------------------------------
    # AMOUNT PAID
    # --------------------------------------------------------
    #
    # Normal purchase:
    # Movie  = 1000
    # Series = 2000
    #
    # Reward purchase:
    # amount = 0

    amount = db.Column(
        db.Numeric(10, 2),
        nullable=False
    )

    # --------------------------------------------------------
    # MERCHANT REFERENCE
    # --------------------------------------------------------
    # Unique reference sent to Pesapal

    merchant_reference = db.Column(
        db.String(100),
        nullable=False,
        unique=True
    )

    # --------------------------------------------------------
    # PESAPAL TRACKING ID
    # --------------------------------------------------------

    order_tracking_id = db.Column(
        db.String(100),
        nullable=True
    )

    # --------------------------------------------------------
    # PAYMENT STATUS
    # --------------------------------------------------------
    #
    # Pending
    # Completed
    # Failed
    # etc.

    payment_status = db.Column(
        db.String(30),
        default='Pending',
        nullable=False
    )

    # --------------------------------------------------------
    # PURCHASE DATE
    # --------------------------------------------------------

    purchased_at = db.Column(
        db.DateTime,
        default=datetime.utcnow,
        nullable=False
    )

    # --------------------------------------------------------
    # ACCESS EXPIRATION
    # --------------------------------------------------------
    #
    # Both movies and series have 30 days of access.
    #
    # The actual 30-day period is calculated in payment.py
    # when Pesapal confirms the payment.

    expires_at = db.Column(
        db.DateTime,
        nullable=True
    )

    # --------------------------------------------------------
    # CHECK ACTIVE PURCHASE
    # --------------------------------------------------------

    def is_active(self):

        """
        Returns True if this purchase:

        1. Was successfully completed
        2. Has an expiration date
        3. Has not expired yet
        """

        return (
            self.payment_status == 'Completed'
            and
            self.expires_at is not None
            and
            self.expires_at > datetime.utcnow()
        )


# ============================================================
# REFERRAL PURCHASE
# ============================================================

class ReferralPurchase(db.Model):

    """
    Records a qualifying purchase made by an invited user.

    Example:

    User A invites User B.

    User B buys a movie.

    A ReferralPurchase record is created:

        inviter_id     = User A
        invited_user_id = User B
        purchase_id    = B's purchase

    This allows us to calculate rewards safely.
    """

    id = db.Column(
        db.Integer,
        primary_key=True
    )

    # --------------------------------------------------------
    # INVITER
    # --------------------------------------------------------
    # User who will receive credit for this purchase.

    inviter_id = db.Column(
        db.Integer,
        db.ForeignKey(
            'user.id',
            ondelete='CASCADE'
        ),
        nullable=False
    )

    # --------------------------------------------------------
    # INVITED USER
    # --------------------------------------------------------
    # User who actually made the purchase.

    invited_user_id = db.Column(
        db.Integer,
        db.ForeignKey(
            'user.id',
            ondelete='CASCADE'
        ),
        nullable=False
    )

    # --------------------------------------------------------
    # PURCHASE
    # --------------------------------------------------------
    # The completed purchase that generated this
    # referral credit.

    purchase_id = db.Column(
        db.Integer,
        db.ForeignKey(
            'purchase.id',
            ondelete='CASCADE'
        ),
        nullable=False,
        unique=True
    )

    # --------------------------------------------------------
    # CREATED DATE
    # --------------------------------------------------------

    created_at = db.Column(
        db.DateTime,
        default=datetime.utcnow,
        nullable=False
    )

    # --------------------------------------------------------
    # RELATIONSHIPS
    # --------------------------------------------------------

    invited_user = db.relationship(
        'User',
        foreign_keys=[invited_user_id],
        backref=db.backref(
            'referral_purchase_records',
            lazy=True
        )
    )

    purchase = db.relationship(
        'Purchase',
        backref=db.backref(
            'referral_purchase',
            uselist=False
        )
    )


# ============================================================
# REWARD
# ============================================================

class Reward(db.Model):

    """
    One free reward earned by an inviter.

    Every 3 qualifying purchases made by the
    inviter's invited users creates ONE Reward.

    Example:

        3 purchases  -> 1 reward
        6 purchases  -> 2 rewards
        9 purchases  -> 3 rewards

    Each reward is stored individually.

    When the user redeems one reward:

        Available -> Used

    This means the user's reward balance decreases
    by exactly 1.
    """

    id = db.Column(
        db.Integer,
        primary_key=True
    )

    # --------------------------------------------------------
    # REWARD OWNER
    # --------------------------------------------------------

    user_id = db.Column(
        db.Integer,
        db.ForeignKey(
            'user.id',
            ondelete='CASCADE'
        ),
        nullable=False
    )

    # --------------------------------------------------------
    # REWARD STATUS
    # --------------------------------------------------------
    #
    # Available = can be used
    # Used      = already redeemed

    status = db.Column(
        db.String(20),
        default='Available',
        nullable=False
    )

    # --------------------------------------------------------
    # WHEN REWARD WAS CREATED
    # --------------------------------------------------------

    created_at = db.Column(
        db.DateTime,
        default=datetime.utcnow,
        nullable=False
    )

    # --------------------------------------------------------
    # WHEN REWARD WAS USED
    # --------------------------------------------------------

    used_at = db.Column(
        db.DateTime,
        nullable=True
    )

    # --------------------------------------------------------
    # WHAT PURCHASE USED THIS REWARD
    # --------------------------------------------------------
    #
    # This will point to the free Purchase created when
    # the reward is redeemed.
    #
    # Nullable because the reward is initially unused.

    used_purchase_id = db.Column(
        db.Integer,
        db.ForeignKey(
            'purchase.id',
            ondelete='SET NULL'
        ),
        nullable=True,
        unique=True
    )

    # --------------------------------------------------------
    # RELATIONSHIP TO REDEMPTION PURCHASE
    # --------------------------------------------------------

    used_purchase = db.relationship(
        'Purchase',
        foreign_keys=[used_purchase_id],
        backref=db.backref(
            'reward_used',
            uselist=False
        )
    )

    # --------------------------------------------------------
    # CHECK IF AVAILABLE
    # --------------------------------------------------------

    def is_available(self):

        return self.status == 'Available'
